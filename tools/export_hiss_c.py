"""Write the v3.8 hiss-band tables as C source for c/sotto_hiss.c.

Usage: python tools/export_hiss_c.py OUT.c

Tables, from sim/data/hiss_band.npz and sim/data/hiss_vowel_fine.npz (both LibriSpeech-trained):
  - the per-class guess of the four 4-8 kHz band levels from the 0-4 kHz envelope (W, 3 x 8 x 4);
  - the 6-bit residual codebook of all-unvoiced frames (cb6, 64 x 4);
  - the vowel-following predictor (16 x 16 ridge weights, bias row first), the mean speaker
    miss m0 (16) and the 3 speaker-shape PCA axes Vt (3 x 16);
  - the 41-tap half-band FIR that scipy.signal.resample_poly(x, 2, 1) and (x, 1, 2) use
    (Kaiser 5.0, cutoff 1/2), so the C resamplers match the Python's;
  - sotto 1200 hiss: the 4 level offsets of an unvoiced B frame (sim/data/lr_hiss_b.npz rel2);
  - sotto 600 / 400 hiss (sim/data/vlr_hiss.npz, [600, 400]): the 8 level slopes of a
    superframe with no pitched frame, the 4 offsets of one with one, and the mean residual of a
    frame without bits over its neighbours' (k2) or with none (h0).
Values are written with 17 significant digits (double).
"""
import os
import sys

import numpy as np
from scipy.signal import firwin

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rows(f, name, a, per_row):
    a = np.asarray(a, float).reshape(-1)
    f.write("const double %s[%d] = {\n" % (name, a.size))
    for i in range(0, a.size, per_row):
        f.write("  " + ", ".join("%.17g" % v for v in a[i:i + per_row]) + ",\n")
    f.write("};\n\n")


def main(out):
    z = np.load(os.path.join(ROOT, "sim", "data", "hiss_band.npz"), allow_pickle=True)
    W = z["W"].item()
    fine = np.load(os.path.join(ROOT, "sim", "data", "hiss_vowel_fine.npz"))
    taps = firwin(41, 0.5, window=("kaiser", 5.0))        # scipy.signal._design_resample_poly
    with open(out, "w") as f:
        f.write("/* Generated by tools/export_hiss_c.py from sim/data/hiss_band.npz,\n"
                " * sim/data/hiss_vowel_fine.npz, sim/data/lr_hiss_b.npz and sim/data/vlr_hiss.npz.\n"
                " * Do not edit. */\n"
                '#include "sotto_hiss_tables.h"\n\n')
        assert all(W[c].shape == (8, 4) for c in range(3)) and z["cb6"].shape == (64, 4)
        rows(f, "sotto_hiss_guess_w", np.stack([W[c] for c in range(3)]), 4)
        rows(f, "sotto_hiss_cb6", z["cb6"], 4)
        assert fine["W"].shape == (16, 16) and fine["m0"].shape == (16,) and fine["Vt"].shape == (3, 16)
        rows(f, "sotto_hiss_fine_w", fine["W"], 8)
        rows(f, "sotto_hiss_fine_m0", fine["m0"], 8)
        rows(f, "sotto_hiss_fine_vt", fine["Vt"], 8)
        rows(f, "sotto_resample_taps", taps, 6)
        lrb = np.load(os.path.join(ROOT, "sim", "data", "lr_hiss_b.npz"))["rel2"]
        assert lrb.shape == (4, 4)
        rows(f, "sotto_lr_hiss_bcb", lrb, 4)
        v = np.load(os.path.join(ROOT, "sim", "data", "vlr_hiss.npz"))
        for name, shape in (("slope", (8,)), ("off", (4, 4)), ("h0", (4,)), ("k2", (4,))):
            t = np.stack([v[f"m{m}_{name}"] for m in ("600", "400")])
            assert t.shape == (2,) + shape
            rows(f, f"sotto_vlr_hiss_{name}", t, 4)


if __name__ == "__main__":
    main(sys.argv[1])
