"""Write the very-low-rate sotto tables (sim/data/vlr_tables.npz) as C for the fixed-point
decoder: c/sotto_vlr_tables.c. The values are sotto_vlr.quantize_tables' (slopes and energy
residuals in 1/16 steps, shape codebooks int8 with one Q16 step per stage), so the Python
reference decodes the same numbers.

Usage: python tools/export_vlr_c.py [--tables sim/data/vlr_tables.npz] [--out c/sotto_vlr_tables.c]
"""
import argparse, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "sim"))
import vlr_tables as vr                                        # noqa: E402


def arr(ctype, name, a, per_line=16):
    a = np.asarray(a).ravel()
    body = ",\n  ".join(", ".join(str(int(v)) for v in a[i:i + per_line]) for i in range(0, len(a), per_line))
    return f"static const {ctype} {name}[{len(a)}] = {{\n  {body}\n}};\n"


def main(tables, out):
    raw = dict(np.load(tables))
    t = vr.quantize_tables(raw)
    src = ["/* Generated by tools/export_vlr_c.py from sim/data/vlr_tables.npz: do not edit.",
           " * Very-low-rate sotto tables (sim/sotto_vlr.py), trained on Speech Commands (CC BY 4.0).",
           " * The shape codebooks are one array, vlr_cb_all (sotto 600's, then sotto 400's), which is",
           " * also the K6's SPI-flash image of them (c/k6/sp_vlr.h); with -DVLR_CB_SPI it is left out",
           " * and the decoder reads them from there (VLR_CB_VEC).",
           " * SPDX-License-Identifier: MIT */",
           '#include "sotto_vlr_tables.h"', ""]
    small, modes, cbs, off = [], [], [], 0
    seen = {}
    for mode in ("600", "400"):
        cfg = vr.MODES[mode]
        p = f"m{mode}_"
        N = cfg["N"]
        assert cfg["be"] == 5 and cfg["bw"] == 7, "the C decoder takes a 5-bit energy mean and 7-bit pitch"
        small.append(arr("unsigned char", f"vpat{mode}", t[p + "vpat"]))
        small.append(arr("int16_t", f"slope{mode}", np.round(t[p + "slope"] * 16)))
        small.append(arr("int16_t", f"eres{mode}", np.round(t[p + "eres"] * 16)))
        # one codebook per distinct (stage bits) group: slots with the same bits share it
        offs, steps = [], []
        for j, (_, bits) in enumerate(cfg["anchors"]):
            ro, st = [], []
            for i, b in enumerate(bits):
                c = np.asarray(raw[f"{p}a{j}s{i}"], float)
                key = (mode, b, c.tobytes())
                if key not in seen:
                    step = np.abs(c).max() / 127
                    q = np.round(c / step).astype(int)
                    cbs.append(q)
                    seen[key] = (off, int(round(step * 65536)))
                    off += q.size
                ro.append(seen[key][0])
                st.append(seen[key][1])
            offs.append(ro)
            steps.append(st)
        na = len(cfg["anchors"])
        aoff = ", ".join(str(o) for o, _ in cfg["anchors"])
        ns = ", ".join(str(len(b)) for _, b in cfg["anchors"])
        sbits = ", ".join("{" + ", ".join(str(x) for x in b) + "}" for _, b in cfg["anchors"])
        cbp = ", ".join("{" + ", ".join(f"VLR_CBP({o})" for o in r) + "}" for r in offs)
        cbo = ", ".join("{" + ", ".join(str(o) for o in r) + "}" for r in offs)
        stp = ", ".join("{" + ", ".join(str(x) for x in s) + "}" for s in steps)
        modes.append(f"const vlr_mode_t vlr_mode{mode} = {{\n  {mode}, {N}, {cfg['bv']}, {cfg['bs']}, {cfg['br']}, {na},\n"
                     f"  vpat{mode}, slope{mode}, eres{mode},\n  {{{aoff}}}, {{{ns}}}, {{{sbits}}},\n"
                     f"  {{{cbp}}},\n  {{{stp}}},\n  {{{cbo}}}\n}};\n")
    src += small
    src.append(f"const uint32_t vlr_cb_bytes = {off};\n")
    src.append("#ifndef VLR_CB_SPI")
    src.append(arr("int8_t", "vlr_cb_all", np.concatenate(cbs), 19).replace("static const", "const"))
    src.append("#define VLR_CBP(o) (vlr_cb_all + (o))\n#else\n#define VLR_CBP(o) 0\n#endif\n")
    src += modes
    open(out, "w").write("\n".join(src))
    print("wrote", out, f"({off} codebook bytes)")


if __name__ == "__main__":
    a = argparse.ArgumentParser()
    a.add_argument("--tables", default=vr.TABLES)
    a.add_argument("--out", default=os.path.join(ROOT, "c", "sotto_vlr_tables.c"))
    a = a.parse_args()
    main(a.tables, a.out)
